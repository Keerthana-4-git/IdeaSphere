/* ==================================================
                        TOAST
================================================== */

function showToast(title, message) {

    document.getElementById(
        "toastTitle"
    ).textContent = title;


    document.getElementById(
        "toastMessage"
    ).textContent = message;


    toast.classList.add(
        "show"
    );


    clearTimeout(
        toastTimer
    );


    toastTimer = setTimeout(() => {

        toast.classList.remove(
            "show"
        );

    }, 3000);

}


