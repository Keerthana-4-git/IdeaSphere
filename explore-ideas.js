/* ==================================================
                UPDATE PREVIEW SAVE BUTTON
================================================== */

function updatePreviewSaveButton() {

    if (!activePreviewIdea) {

        return;

    }


    const saved =
        isIdeaSaved(
            activePreviewIdea.id
        );


    previewSaveBtn.classList.toggle(
        "saved",
        saved
    );


    previewSaveBtn.innerHTML = `

        <i class="${
            saved
                ? "fa-solid"
                : "fa-regular"
        } fa-heart"></i>

        ${
            saved
                ? "Saved"
                : "Save Idea"
        }

    `;

}


