/* ==================================================
                    FILTER IDEAS
================================================== */

function getFilteredIdeas() {

    const searchValue =
        searchInput.value
            .trim()
            .toLowerCase();


    const selectedStage =
        stageFilter.value.trim();


    let filteredIdeas =
        exploreIdeas.filter(idea => {


            const searchableContent = `

                ${idea.title}

                ${idea.category}

                ${idea.stage}

                ${idea.description}

                ${idea.problem}

                ${idea.solution}

                ${idea.audience}

                ${idea.tags.join(" ")}

            `.toLowerCase();


            const matchesSearch =

                searchValue === "" ||

                searchableContent.includes(
                    searchValue
                );


            const matchesCategory =

                selectedCategory === "All" ||

                idea.category === selectedCategory;


            const matchesStage =

                selectedStage === "All" ||

                idea.stage.toLowerCase() ===
                selectedStage.toLowerCase();


            return (

                matchesSearch &&

                matchesCategory &&

                matchesStage

            );

        });


    /* ==================================================
                        SORTING
    ================================================== */

    const sortValue =
        sortFilter.value;


    if (sortValue === "trending") {

        filteredIdeas.sort(

            (a, b) =>

                getDiscoveryScore(b) -
                getDiscoveryScore(a)

        );

    }


    else if (sortValue === "popular") {

        /*
            IdeaSphere currently has no real
            community engagement backend.

            Therefore "Most Popular" uses saved
            status in this browser as the only
            real interaction signal.
        */

        filteredIdeas.sort((a, b) => {

            const aSaved =
                Number(isIdeaSaved(a.id));


            const bSaved =
                Number(isIdeaSaved(b.id));


            if (aSaved !== bSaved) {

                return bSaved - aSaved;

            }


            return (

                getDiscoveryScore(b) -
                getDiscoveryScore(a)

            );

        });

    }


    else if (sortValue === "newest") {

        filteredIdeas.sort(

            (a, b) =>

                b.createdOrder -
                a.createdOrder

        );

    }


    else if (sortValue === "az") {

        filteredIdeas.sort(

            (a, b) =>

                a.title.localeCompare(
                    b.title
                )

        );

    }


    return filteredIdeas;

}


/* ==================================================
                    RENDER IDEAS
================================================== */

function renderIdeas() {

    const filteredIdeas =
        getFilteredIdeas();


    visibleCount.textContent =
        filteredIdeas.length;


    ideaCount.textContent =
        exploreIdeas.length;


    if (filteredIdeas.length === 0) {

        ideasGrid.innerHTML = "";


        emptyState.classList.add(
            "show"
        );


        return;

    }


    emptyState.classList.remove(
        "show"
    );


    ideasGrid.innerHTML =

        filteredIdeas

            .map(

                (idea, index) =>

                    createIdeaCard(
                        idea,
                        index
                    )

            )

            .join("");

}


/* ==================================================
                    TOGGLE SAVE
================================================== */

function toggleSaveIdea(id) {

    const idea =
        exploreIdeas.find(

            item =>

                String(item.id) === String(id)

        );


    if (!idea) {

        return;

    }


    let savedIdeas =
        getExploreSavedIdeas();


    const savedIndex =
        savedIdeas.findIndex(

            item =>

                String(item.id) === String(id)

        );


    if (savedIndex === -1) {

        savedIdeas.push({

            ...idea,

            source: "explore",

            savedAt: new Date().toISOString()

        });


        saveExploreSavedIdeas(
            savedIdeas
        );


        showToast(

            "Idea Saved",

            `${idea.title} was added to your saved ideas.`

        );

    }
    else {

        savedIdeas.splice(
            savedIndex,
            1
        );


        saveExploreSavedIdeas(
            savedIdeas
        );


        showToast(

            "Idea Removed",

            `${idea.title} was removed from saved ideas.`

        );

    }


    renderIdeas();


    if (

        activePreviewIdea &&

        String(activePreviewIdea.id) ===
        String(id)

    ) {

        updatePreviewSaveButton();

    }

}


