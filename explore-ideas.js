/* ==================================================
                LOCAL STORAGE HELPERS
================================================== */

function readLocalStorage(key) {

    try {

        return JSON.parse(
            localStorage.getItem(key)
        ) || [];

    }
    catch (error) {

        return [];

    }

}


function writeLocalStorage(key, value) {

    localStorage.setItem(
        key,
        JSON.stringify(value)
    );

}


/* ==================================================
                    SAVED IDEAS
================================================== */

function getExploreSavedIdeas() {

    return readLocalStorage(
        "exploreSavedIdeas"
    );

}


function saveExploreSavedIdeas(savedIdeas) {

    writeLocalStorage(
        "exploreSavedIdeas",
        savedIdeas
    );

}


function isIdeaSaved(id) {

    return getExploreSavedIdeas().some(

        idea =>

            String(idea.id) === String(id)

    );

}


